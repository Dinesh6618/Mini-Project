"""Data Ethics page."""

from __future__ import annotations

import streamlit as st

from views.common import page_header

SECTIONS = [
    (
        "Student data privacy and security",
        "Academic records are personal data. Process only data you are authorised to use, keep "
        "files on a protected device, share the minimum needed, and remove direct identifiers "
        "(names, IDs) when they are not required.",
        "Everything runs locally with no cloud service. Anonymous IDs are on by default and "
        "hide names. The optional SQLite file excludes names unless you tick a box, and "
        "`data/*.db` is excluded from git.",
    ),
    (
        "Informed and appropriate use",
        "Students and staff should know what data is collected, why it is analysed and who "
        "sees the results. Data gathered for teaching support should not quietly be reused for "
        "discipline, ranking or any unrelated purpose.",
        "The app describes its purpose on every prediction view and frames outputs as prompts "
        "for supportive follow-up. Obtaining consent and following your institution's policy "
        "remains your responsibility.",
    ),
    (
        "Bias in data and algorithms",
        "Past outcomes can reflect unequal opportunities, inconsistent grading or missing "
        "context. A model trained on them can repeat those patterns, and groups with few "
        "records are modelled less reliably.",
        "Department, year and section are not used as model inputs. Check results across "
        "groups, where lawful and appropriate, before relying on them; this demo does not "
        "include a fairness audit.",
    ),
    (
        "Transparency and explainability",
        "People affected by an analysis should be able to understand roughly how it works. "
        "Simple, inspectable methods are preferable to opaque ones for decisions about people.",
        "Thresholds are visible and adjustable, Logistic Regression coefficients and Decision "
        "Tree importances are shown, single predictions list what raised or lowered the "
        "estimate, and recommendations come from plain rules.",
    ),
    (
        "Limitations of predictive analytics",
        "A model sees only the columns it is given. It cannot see effort, health, family "
        "circumstances or the support a student received, and a score is a statistical "
        "estimate about groups of similar past students, not a fact about an individual. "
        "Correlation is not causation.",
        "Metrics come from a held-out test set and are labelled with warnings for small, "
        "imbalanced or synthetic data. The sample dataset's outcomes were generated by an "
        "artificial rule, so its scores must not be read as real-world accuracy.",
    ),
    (
        "Human oversight in academic decisions",
        "Model outputs must never be the sole basis for academic, disciplinary or resource "
        "decisions. A person who knows the student should review any flag, listen to the "
        "student and be able to override the model.",
        "The app only suggests supportive conversations and extra help. It does not rank, label "
        "or penalise students, and it does not infer personal circumstances from marks.",
    ),
]


def render(ctx) -> None:
    page_header(
        "Data Ethics",
        "Using student data responsibly matters as much as the accuracy of any model.",
    )
    st.error(
        "Model outputs must never be the sole basis for an academic decision about a student. "
        "They are estimates intended to start human conversations about support."
    )
    for title, principle, practice in SECTIONS:
        with st.container(border=True):
            st.subheader(title)
            st.markdown(f"**Principle.** {principle}")
            st.markdown(f"**In this application.** {practice}")

    st.subheader("Checklist before using real data")
    st.markdown(
        "- [ ] I have permission from the institution to analyse this data.\n"
        "- [ ] Students and staff have been informed about the purpose.\n"
        "- [ ] Names and direct identifiers are removed unless essential.\n"
        "- [ ] The file is stored securely and not shared publicly.\n"
        "- [ ] Results will be reviewed by a person before any action is taken.\n"
        "- [ ] Results have been checked for uneven performance across groups.\n"
        "- [ ] Students can ask how their data was used and question outcomes."
    )
